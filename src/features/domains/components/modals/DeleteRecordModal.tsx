import React, { useState } from 'react';
import { CircleNotch, Lock, Trash, WarningCircle } from '@phosphor-icons/react';
import { BaseModal } from '../../../../shared/components/modals/BaseModal';
import type { DomainRecordItem } from '../../types/domains.types';

interface DeleteRecordModalProps {
  isOpen: boolean;
  record: DomainRecordItem | null;
  onClose: () => void;
  onConfirm: (record: DomainRecordItem) => Promise<void>;
}

export const DeleteRecordModal: React.FC<DeleteRecordModalProps> = ({
  isOpen,
  record,
  onClose,
  onConfirm,
}) => {
  const [isDeleting, setIsDeleting] = useState(false);
  const [error, setError] = useState<string | null>(null);
  const [forceUnlock, setForceUnlock] = useState(false);

  if (!record) return null;

  const handleConfirm = async () => {
    if (record.locked && !forceUnlock) {
      setError('Please confirm that you understand this is a Cloudflare system record before deleting.');
      return;
    }

    setIsDeleting(true);
    setError(null);
    try {
      await onConfirm(record);
      onClose();
    } catch (err) {
      setError(err instanceof Error ? err.message : 'Failed to delete record.');
    } finally {
      setIsDeleting(false);
    }
  };

  const isDeleteDisabled = isDeleting || (record.locked && !forceUnlock);

  return (
    <BaseModal
      isOpen={isOpen}
      onClose={onClose}
      title={record.locked ? 'Delete Cloudflare System Record' : 'Delete DNS Record'}
      subtitle={`Are you sure you want to remove ${record.name}?`}
      icon={
        record.locked ? (
          <Lock size={18} weight="bold" className="text-amber-400" />
        ) : (
          <Trash size={18} weight="bold" className="text-danger" />
        )
      }
      maxWidthClass="max-w-md"
      footer={
        <div className="flex items-center justify-end gap-2 w-full">
          <button
            type="button"
            onClick={onClose}
            disabled={isDeleting}
            className="rounded-lg border border-default bg-elevated px-3 py-1.5 text-xs font-medium text-fg-secondary hover:text-fg-primary hover:border-strong transition-colors cursor-pointer disabled:opacity-50"
          >
            Cancel
          </button>
          <button
            type="button"
            onClick={handleConfirm}
            disabled={isDeleteDisabled}
            className="flex items-center gap-1.5 rounded-lg bg-danger px-3 py-1.5 text-xs font-semibold text-white hover:bg-danger/90 transition-colors cursor-pointer disabled:opacity-50 shadow-xs"
          >
            {isDeleting && <CircleNotch size={13} weight="bold" className="animate-spin" />}
            <span>{isDeleting ? 'Deleting...' : 'Delete Record'}</span>
          </button>
        </div>
      }
    >
      <div className="space-y-3.5">
        {/* Warning if record is managed / locked by Cloudflare */}
        {record.locked && (
          <div className="rounded-xl border border-amber-500/30 bg-amber-500/10 p-3 text-xs space-y-2">
            <div className="flex items-center gap-2 font-bold text-amber-400">
              <WarningCircle size={17} weight="bold" className="shrink-0" />
              <span>Cloudflare Managed Record (Locked)</span>
            </div>
            <p className="text-fg-secondary text-[11px] leading-relaxed">
              This record was automatically generated by Cloudflare services (such as <strong>Cloudflare Email Routing</strong>, <strong>SSL/TLS Certificates</strong>, or <strong>Domain Delegation</strong>). Deleting it will cause active emails or security services to immediately fail.
            </p>
            <label className="flex items-start gap-2 pt-1 cursor-pointer select-none">
              <input
                type="checkbox"
                checked={forceUnlock}
                onChange={(e) => setForceUnlock(e.target.checked)}
                className="mt-0.5 rounded border-default text-accent focus:ring-accent-ring cursor-pointer"
              />
              <span className="text-[11px] text-amber-300 font-semibold">
                I understand this is a Cloudflare system record and want to unlock deletion.
              </span>
            </label>
          </div>
        )}

        <p className="text-xs text-fg-secondary leading-relaxed">
          This will delete the <span className="font-mono font-bold text-fg-primary">{record.type}</span> record for <strong className="font-mono text-fg-primary">{record.name}</strong> pointing to <code className="text-accent">{record.content}</code>.
        </p>

        <p className="text-xs text-fg-muted">
          Traffic addressed to this host or subdomain will immediately cease resolving.
        </p>

        {error && (
          <div className="rounded-lg bg-danger/10 border border-danger/20 p-2.5 text-xs text-danger font-medium">
            {error}
          </div>
        )}
      </div>
    </BaseModal>
  );
};
